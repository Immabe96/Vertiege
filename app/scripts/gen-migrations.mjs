#!/usr/bin/env node
/**
 * Bundle Drizzle's generated SQL into a TS module Metro can actually import.
 *
 * `drizzle-kit generate` writes `db/migrations/*.sql` + `meta/_journal.json`.
 * `drizzle-orm/expo-sqlite/migrator` wants `{ journal, migrations }` in memory,
 * and Metro cannot import raw `.sql`. Run automatically by `npm run db:generate`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const migrationsDir = join(root, 'db', 'migrations');
const outFile = join(root, 'db', 'migrations.generated.ts');

const journal = JSON.parse(readFileSync(join(migrationsDir, 'meta', '_journal.json'), 'utf8'));

const migrations = {};
for (const entry of journal.entries) {
  const key = `m${String(entry.idx).padStart(4, '0')}`;
  migrations[key] = readFileSync(join(migrationsDir, `${entry.tag}.sql`), 'utf8');
}

const banner = '// AUTO-GENERATED by scripts/gen-migrations.mjs — do not edit by hand.\n';
writeFileSync(outFile, `${banner}export default ${JSON.stringify({ journal, migrations }, null, 2)};\n`);

console.log(`✓ ${Object.keys(migrations).length} migration(s) → db/migrations.generated.ts`);
